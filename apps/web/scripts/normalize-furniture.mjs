// Normalizes downloaded furniture models to the viewer's conventions:
// real-world metres, glTF Y-up, long side along X, standing on the floor
// with its footprint centred on the origin. See assets/furniture/models.json.
//
//   pnpm --filter web normalize-furniture [model-id ...]

import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { NodeIO } from '@gltf-transform/core'
import { ALL_EXTENSIONS } from '@gltf-transform/extensions'
import { dedup, getBounds, prune } from '@gltf-transform/functions'

const REPO_ROOT = fileURLToPath(new URL('../../../', import.meta.url))
const FURNITURE_DIR = join(REPO_ROOT, 'assets/furniture')
const SOURCE_DIR = join(FURNITURE_DIR, 'source')
const OUTPUT_DIR = join(REPO_ROOT, 'apps/web/public/models/furniture')

const manifest = JSON.parse(await readFile(join(FURNITURE_DIR, 'models.json'), 'utf8'))
const only = new Set(process.argv.slice(2))
const io = new NodeIO().registerExtensions(ALL_EXTENSIONS)
await mkdir(OUTPUT_DIR, { recursive: true })

const rows = []
const credits = []
for (const model of manifest.models) {
  if (only.size > 0 && !only.has(model.id)) continue
  const document = await io.read(join(SOURCE_DIR, model.source))
  const root = document.getRoot()
  const scene = root.getDefaultScene() ?? root.listScenes()[0]
  const before = size(getBounds(scene))

  // Hang everything off one new node, so the source's own transforms (often
  // a Z-up-to-Y-up turn from the exporter) stay intact underneath ours.
  const pivot = document.createNode(model.id)
  for (const child of scene.listChildren()) {
    scene.removeChild(child)
    pivot.addChild(child)
  }
  scene.addChild(pivot)

  const scale = model.scale ?? model.height_m / before[1]
  if (!Number.isFinite(scale) || scale <= 0) throw new Error(`${model.id}: give a positive "scale" or "height_m"`)
  // Long side along X, so it lines up with a detected box's width.
  const yaw = (before[0] >= before[2] ? 0 : 90) + (model.yaw_degrees ?? 0)
  const half = (yaw * Math.PI) / 360
  pivot.setScale([scale, scale, scale]).setRotation([0, Math.sin(half), 0, Math.cos(half)])

  // Then stand it on the floor, footprint centred on the origin.
  const { min, max } = getBounds(scene)
  pivot.setTranslation([-(min[0] + max[0]) / 2, -min[1], -(min[2] + max[2]) / 2])
  const after = size(getBounds(scene))

  const credit = model.credit ?? root.getAsset().extras ?? {}
  root.getAsset().extras = {
    ...credit,
    tflop: { id: model.id, category: model.category, source: model.source, size_m: after },
  }
  await document.transform(prune(), dedup())

  const output = join(OUTPUT_DIR, `${model.id}.glb`)
  const bytes = await io.writeBinary(document)
  await writeFile(output, bytes)
  rows.push({ id: model.id, before, scale, after, mb: bytes.byteLength / 1e6 })
  credits.push({ id: model.id, ...credit })
}

const format = (dims) => dims.map((value) => value.toFixed(2)).join(' x ')
console.log('id'.padEnd(18), 'source size'.padEnd(24), 'scale'.padEnd(8), 'result (w x h x d, m)'.padEnd(22), 'MB')
for (const row of rows) {
  console.log(
    row.id.padEnd(18),
    format(row.before).padEnd(24),
    String(+row.scale.toPrecision(3)).padEnd(8),
    format(row.after).padEnd(22),
    row.mb.toFixed(1),
  )
}

if (only.size === 0) {
  await writeFile(join(FURNITURE_DIR, 'CREDITS.md'), creditsMarkdown(credits))
  console.log(`Wrote ${rows.length} model(s) to ${OUTPUT_DIR} and credits to assets/furniture/CREDITS.md`)
}

function size({ min, max }) {
  return max.map((value, axis) => value - min[axis])
}

function creditsMarkdown(entries) {
  const lines = [
    '# Furniture model credits',
    '',
    'Generated by `pnpm --filter web normalize-furniture` from each model\'s',
    'embedded metadata or `assets/furniture/models.json`.',
    '',
    '| Model | Title | Author | License | Source |',
    '| --- | --- | --- | --- | --- |',
  ]
  for (const entry of entries) {
    lines.push(
      `| \`${entry.id}\` | ${entry.title ?? '-'} | ${entry.author ?? '-'} | ${entry.license ?? '-'} | ${entry.source ?? '-'} |`,
    )
  }
  return `${lines.join('\n')}\n`
}
